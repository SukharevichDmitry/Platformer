package com.cursedarchie.platformer.physics;

public class AttackConfig {
    public float width;
    public float height;
    public float offsetX;
    public float offsetY;

    public AttackConfig() {}

    public AttackConfig(float width, float height, float offsetX, float offsetY) {
        this.width = width;
        this.height = height;
        this.offsetX = offsetX;
        this.offsetY = offsetY;
    }
}
